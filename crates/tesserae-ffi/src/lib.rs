/// The version of this ABI. Bumped on any change to a struct layout, a
/// function signature or the meaning of a constant. The app compares it with
/// the `TESS_ABI_VERSION` it was compiled against and refuses to run on a
/// mismatch: drift is a build defect, not a user condition.
pub const TESS_ABI_VERSION: u32 = 1;

/// `TessNode.flags` bit: the node is a directory.
pub const TESS_FLAG_DIR: u16 = 1 << 0;
/// `TessNode.flags` bit: the node is a symbolic link (never followed).
pub const TESS_FLAG_SYMLINK: u16 = 1 << 1;
/// `TessNode.flags` bit: a hardlink counted as zero bytes because an earlier
/// link to the same inode already carried them.
pub const TESS_FLAG_HARDLINK_DUP: u16 = 1 << 2;
/// `TessNode.flags` bit: a directory that could not be read for lack of
/// permission, so it holds no children and no bytes.
pub const TESS_FLAG_PERM_DENIED: u16 = 1 << 3;
/// `TessNode.flags` bit: a node standing for several siblings merged by the
/// treemap's tail aggregation. Set by the app's layout, never by a scan.
pub const TESS_FLAG_AGGREGATED: u16 = 1 << 4;

/// `TessNode.parent` of the root, and `TessView.root` of a snapshot that holds
/// no nodes.
pub const TESS_NODE_NONE: u32 = u32::MAX;

/// `TessScanStats.incomplete`: the scan covered everything it was asked to.
pub const TESS_INCOMPLETE_NONE: u32 = 0;
/// `TessScanStats.incomplete`: the scan was cancelled; the snapshot is partial.
pub const TESS_INCOMPLETE_CANCELLED: u32 = 1;
/// `TessScanStats.incomplete`: the scan reached its node budget and stopped.
pub const TESS_INCOMPLETE_NODE_BUDGET: u32 = 2;
/// `TessScanStats.incomplete`: the scan ran out of memory and stopped.
pub const TESS_INCOMPLETE_OUT_OF_MEMORY: u32 = 3;
/// `TessScanStats.incomplete`: a volume hung, and the scan gave up on it. See
/// `tess_snapshot_stalled_at`.
pub const TESS_INCOMPLETE_STALLED: u32 = 4;
/// `TessScanStats.incomplete`: the scan ran out of file descriptors; some
/// subtrees are missing from the totals.
pub const TESS_INCOMPLETE_FD_EXHAUSTED: u32 = 5;
/// `TessScanStats.incomplete`: the kernel returned a directory batch that
/// could not be parsed; `lost_entries` says how many entries were lost.
pub const TESS_INCOMPLETE_MALFORMED_BATCH: u32 = 6;
/// `TessScanStats.incomplete`: the volume being scanned went away mid-scan (an
/// image detached, a drive pulled); the snapshot holds what was read before.
pub const TESS_INCOMPLETE_VOLUME_LOST: u32 = 7;

/// `tess_scan_status`: the scan is still running.
pub const TESS_STATUS_RUNNING: i32 = 0;
/// `tess_scan_status`: the scan has finished, so `tess_scan_finish` will not
/// block. (A negative status is the scan's failure, as a negated errno.)
pub const TESS_STATUS_FINISHED: i32 = 1;

// The flag bits and the node sentinel are the core's, restated here as
// literals the header can export. A change on either side must fail the build
// rather than leave the header describing a layout the engine does not write.
const _: () = {
    use tesserae_core::arena::{FLAG_HARDLINK_DUP, FLAG_PERM_DENIED};
    use tesserae_core::node::{FLAG_AGGREGATED, FLAG_DIR, FLAG_SYMLINK, NODE_NONE};
    assert!(TESS_FLAG_DIR == FLAG_DIR);
    assert!(TESS_FLAG_SYMLINK == FLAG_SYMLINK);
    assert!(TESS_FLAG_HARDLINK_DUP == FLAG_HARDLINK_DUP);
    assert!(TESS_FLAG_PERM_DENIED == FLAG_PERM_DENIED);
    assert!(TESS_FLAG_AGGREGATED == FLAG_AGGREGATED);
    assert!(TESS_NODE_NONE == NODE_NONE);
};

/// A scan in progress. Opaque: the app only holds the pointer.
pub struct TessScan {
    progress: Arc<Progress>,
    status: Arc<AtomicI32>,
    thread: JoinHandle<Result<Snapshot, i32>>,
}

/// A frozen, immutable snapshot. Opaque: the app reads it through
/// `tess_snapshot_view` and the accessors beside it.
pub struct TessSnapshot(Snapshot);

/// A borrowed view of a snapshot's arrays. The pointers stay valid until
/// `tess_snapshot_release` is called on the snapshot they came from.
#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct TessView {
    /// `count` nodes, root at index `root`; null when `count` is 0.
    pub nodes: *const TessNode,
    pub count: u64,
    /// `names_len` bytes of node names, addressed by `name_off` and `name_len`.
    /// Arbitrary bytes, not necessarily UTF-8; null when `names_len` is 0.
    pub names: *const u8,
    pub names_len: u64,
    /// Index of the root node, or `TESS_NODE_NONE` if there are no nodes.
    pub root: u32,
}

/// What a scan has found so far; see `tess_scan_progress`.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TessProgress {
    pub dirs_done: u64,
    pub files_done: u64,
    /// Allocated bytes of everything stored so far.
    pub bytes_seen: u64,
    pub errors: u64,
}

/// Scan settings. Every field's zero value means "the default", so a
/// zero-filled struct and a null pointer both give a default scan.
#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct TessScanOptions {
    /// The deepest level recorded; the root is depth 0. 0 means 512.
    pub max_depth: u16,
    /// Whether to descend into network and other non-local mounts: 0 means no
    /// (the default), any other value yes. Another local volume is never
    /// entered either way. A byte, not a C `bool`, so that no value a C caller
    /// can write is invalid.
    pub include_non_local: u8,
    /// Worker thread count. 0 means one per core, between 4 and 16. A larger
    /// value is capped at 64, and fewer are run if the descriptor limit cannot
    /// feed that many.
    pub workers: u32,
    /// Most nodes the scan may store. 0 means 25 million.
    pub node_budget: u64,
    /// Size of each worker's directory-read buffer. 0 means 256 KiB.
    pub buffer_bytes: u64,
    /// How long a scan may go without completing a single syscall before it is
    /// declared stalled, in milliseconds. 0 means 15000.
    pub stall_timeout_ms: u64,
}

/// What a finished scan saw; see `tess_snapshot_stats`.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TessScanStats {
    /// 0 if the scan is complete, otherwise one of the `TESS_INCOMPLETE_*`
    /// codes saying why the snapshot is partial.
    pub incomplete: u32,
    /// Non-directory nodes: files, symlinks and special files.
    pub files: u64,
    /// Directory nodes, the root included.
    pub dirs: u64,
    /// Failures that were absorbed and did not stop the scan: races and other
    /// errors that are neither a permission denial nor fatal.
    pub errors: u64,
    /// Directories that could not be read for lack of permission.
    pub unreadable_count: u64,
    /// Directories not entered because they are another volume's mount point
    /// or a non-local mount the options did not opt into.
    pub skipped_mounts_count: u64,
    /// Entries the kernel returned that the parser rejected or never reached.
    pub lost_entries: u64,
    /// Hardlinks counted as zero bytes because another link carried them.
    pub hardlink_dups: u64,
    /// Directories recorded at `max_depth` and therefore not entered.
    pub depth_capped: u64,
}

/// Run `f`, returning `on_panic` if it panics. The one `catch_unwind` every
/// entry point and the scan thread go through. The closure is asserted
/// unwind-safe because nothing it touches is observed after a panic except
/// through the same atomics and handles it already shares.
fn guarded<R>(on_panic: R, f: impl FnOnce() -> R) -> R {
    catch_unwind(AssertUnwindSafe(f)).unwrap_or(on_panic)
}

/// The version of this ABI; see `TESS_ABI_VERSION`.
#[unsafe(no_mangle)]
pub extern "C" fn tess_abi_version() -> u32 {
    guarded(0, || TESS_ABI_VERSION)
}

/// Start scanning `root` and return at once with a handle to the running scan.
///
/// `root` is a NUL-terminated path. It is bytes, not text: it need not be
/// UTF-8. `options` may be null, which means every default. Returns null if
/// `root` is null or empty or the scan thread could not be started. A root that
/// does not exist or cannot be opened is not refused here: the scan fails, and
/// `tess_scan_status` says why.
///
/// Every scan must end in exactly one call to `tess_scan_finish`, which is also
/// what frees the handle; to abandon a scan, `tess_scan_cancel` it first.
///
/// # Threads
///
/// `tess_scan_progress`, `tess_scan_cancel` and `tess_scan_status` may be
/// called from any thread, concurrently, while the scan runs. `tess_scan_finish`
/// consumes the handle and must not race any other call on it.
///
/// # Safety
///
/// `root` must be null or point to a NUL-terminated string. `options` must be
/// null or point to a `TessScanOptions`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_scan_begin(
    root: *const c_char,
    options: *const TessScanOptions,
) -> *mut TessScan {
    guarded(ptr::null_mut(), || {
        if root.is_null() {
            return ptr::null_mut();
        }
        // SAFETY: the caller promises a NUL-terminated string.
        let root = unsafe { CStr::from_ptr(root) }.to_bytes();
        if root.is_empty() {
            return ptr::null_mut();
        }
        // SAFETY: the caller promises null or a live struct.
        let options = unsafe { options.as_ref() };
        let opts = walk_options(OsStr::from_bytes(root), options);
        start(opts).map_or(ptr::null_mut(), |scan| Box::into_raw(Box::new(scan)))
    })
}

/// Copy the scan's counters into `out`. Never blocks. A null `scan` writes
/// zeros; a null `out` does nothing. After the scan has finished the counters
/// are exact.
///
/// # Safety
///
/// `scan` must be null or a handle from `tess_scan_begin` that has not been
/// passed to `tess_scan_finish`. `out` must be null or point to a
/// `TessProgress`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_scan_progress(scan: *mut TessScan, out: *mut TessProgress) {
    guarded((), || {
        if out.is_null() {
            return;
        }
        // SAFETY: the caller promises null or a live scan.
        let seen = unsafe { scan.as_ref() }.map(|s| s.progress.snapshot());
        let seen = seen.map_or(
            TessProgress {
                dirs_done: 0,
                files_done: 0,
                bytes_seen: 0,
                errors: 0,
            },
            |v| TessProgress {
                dirs_done: v.dirs,
                files_done: v.files,
                bytes_seen: v.bytes,
                errors: v.errors,
            },
        );
        // SAFETY: the caller promises `out` is writable.
        unsafe { out.write(seen) };
    })
}

/// Ask the scan to stop. Returns at once; the scan stops at its next directory
/// boundary, and `tess_scan_finish` then returns what it gathered, flagged
/// incomplete. Safe to call more than once, and after the scan has finished.
///
/// # Safety
///
/// `scan` must be null or a handle from `tess_scan_begin` that has not been
/// passed to `tess_scan_finish`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_scan_cancel(scan: *mut TessScan) {
    guarded((), || {
        // SAFETY: the caller promises null or a live scan.
        if let Some(scan) = unsafe { scan.as_ref() } {
            scan.progress.cancel();
        }
    })
}

/// Whether the scan is done: `TESS_STATUS_RUNNING` (0), `TESS_STATUS_FINISHED`
/// (1; `tess_scan_finish` will not block), or a negated errno if the scan
/// failed (`tess_scan_finish` will return null). A null `scan` is `-EINVAL`.
/// For a root that could not be opened the errno is the one the operating
/// system reported, so `-EPERM` (macOS refusing access to a protected folder)
/// and `-EACCES` (ordinary file permissions) stay distinct.
///
/// A scan that failed because its walk panicked is `-EIO`. Poll this rather
/// than blocking in `tess_scan_finish`: after a cancel, finish is prompt except
/// when the root itself hangs in `open`.
///
/// # Safety
///
/// `scan` must be null or a handle from `tess_scan_begin` that has not been
/// passed to `tess_scan_finish`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_scan_status(scan: *const TessScan) -> i32 {
    guarded(-libc::EIO, || {
        // SAFETY: the caller promises null or a live scan.
        match unsafe { scan.as_ref() } {
            Some(scan) => scan.status.load(Ordering::Acquire),
            None => -libc::EINVAL,
        }
    })
}

/// Wait for the scan to end, free the handle, and return the snapshot, or null
/// if the scan failed (or `scan` is null). The handle is consumed either way:
/// do not use it again.
///
/// A cancelled scan is not a failure: it returns a partial snapshot whose
/// `TessScanStats.incomplete` says so. This blocks until the scan thread ends,
/// which after `tess_scan_cancel` is prompt unless the root itself hangs in
/// `open`; to avoid blocking at all, poll `tess_scan_status` until it is not
/// `TESS_STATUS_RUNNING` and finish then.
///
/// # Safety
///
/// `scan` must be null or a handle from `tess_scan_begin` that has not already
/// been passed to this function, and no other call may use it concurrently.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_scan_finish(scan: *mut TessScan) -> *mut TessSnapshot {
    guarded(ptr::null_mut(), || {
        if scan.is_null() {
            return ptr::null_mut();
        }
        // SAFETY: the caller promises a live handle it will not use again.
        let scan = unsafe { Box::from_raw(scan) };
        match scan.thread.join() {
            Ok(Ok(snapshot)) => Box::into_raw(Box::new(TessSnapshot(snapshot))),
            // A failed scan, or a thread that died despite its own guard.
            Ok(Err(_)) | Err(_) => ptr::null_mut(),
        }
    })
}

/// Fill `out` with pointers into the snapshot. The view is borrowed: it, and
/// every pointer in it, is valid until `tess_snapshot_release` and not after.
/// The snapshot is immutable, so a view may be read from any thread.
///
/// A null `snapshot` writes an empty view (null arrays, zero lengths, root
/// `TESS_NODE_NONE`); a null `out` does nothing.
///
/// # Safety
///
/// `snapshot` must be null or a snapshot from `tess_scan_finish` that has not
/// been released. `out` must be null or point to a `TessView`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_snapshot_view(snapshot: *const TessSnapshot, out: *mut TessView) {
    guarded((), || {
        if out.is_null() {
            return;
        }
        // SAFETY: the caller promises null or a live snapshot.
        let view = match unsafe { snapshot.as_ref() } {
            Some(TessSnapshot(s)) => TessView {
                nodes: slice_ptr(&s.nodes),
                count: s.nodes.len() as u64,
                names: slice_ptr(&s.names),
                names_len: s.names.len() as u64,
                root: s.root,
            },
            None => TessView {
                nodes: ptr::null(),
                count: 0,
                names: ptr::null(),
                names_len: 0,
                root: TESS_NODE_NONE,
            },
        };
        // SAFETY: the caller promises `out` is writable.
        unsafe { out.write(view) };
    })
}

/// Copy what the scan saw into `out`: whether the snapshot is partial and why,
/// and the counts a UI reports. A null `snapshot` writes zeros; a null `out`
/// does nothing.
///
/// # Safety
///
/// `snapshot` must be null or a snapshot from `tess_scan_finish` that has not
/// been released. `out` must be null or point to a `TessScanStats`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_snapshot_stats(
    snapshot: *const TessSnapshot,
    out: *mut TessScanStats,
) {
    guarded((), || {
        if out.is_null() {
            return;
        }
        // SAFETY: the caller promises null or a live snapshot.
        let stats = match unsafe { snapshot.as_ref() } {
            Some(TessSnapshot(s)) => scan_stats(&s.stats),
            None => scan_stats(&WalkStats::default()),
        };
        // SAFETY: the caller promises `out` is writable.
        unsafe { out.write(stats) };
    })
}

/// The directory a hung volume stopped the scan at, as an absolute path, when
/// `TessScanStats.incomplete` is `TESS_INCOMPLETE_STALLED`. Returns a pointer
/// to `*len_out` bytes borrowed from the snapshot, valid until
/// `tess_snapshot_release`. The bytes are a path, not text: not NUL-terminated,
/// and not necessarily UTF-8.
///
/// Returns null, with `*len_out` set to 0, when there is no such path (and when
/// `snapshot` is null). Returns null if `len_out` is null.
///
/// # Safety
///
/// `snapshot` must be null or a snapshot from `tess_scan_finish` that has not
/// been released. `len_out` must be null or point to a `uint64_t`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_snapshot_stalled_at(
    snapshot: *const TessSnapshot,
    len_out: *mut u64,
) -> *const u8 {
    guarded(ptr::null(), || {
        if len_out.is_null() {
            return ptr::null();
        }
        // SAFETY: the caller promises null or a live snapshot.
        let path = unsafe { snapshot.as_ref() }
            .and_then(|TessSnapshot(s)| s.stats.stalled_at.as_deref())
            .map(|p| p.as_os_str().as_bytes());
        // SAFETY: the caller promises `len_out` is writable.
        unsafe { len_out.write(path.map_or(0, |p| p.len() as u64)) };
        path.map_or(ptr::null(), <[u8]>::as_ptr)
    })
}

/// Free the snapshot. Every view, and every pointer taken from it or from
/// `tess_snapshot_stalled_at`, is invalid afterwards. A null `snapshot` does
/// nothing. Call it exactly once per snapshot.
///
/// # Safety
///
/// `snapshot` must be null or a snapshot from `tess_scan_finish` that has not
/// already been released, and nothing may be reading it concurrently.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn tess_snapshot_release(snapshot: *mut TessSnapshot) {
    guarded((), || {
        if !snapshot.is_null() {
            // SAFETY: the caller promises a live snapshot it will not use again.
            drop(unsafe { Box::from_raw(snapshot) });
        }
    })
}

/// A pointer to the first element, or null for an empty slice (whose own
/// pointer is dangling, which a C caller could mistake for an address).
fn slice_ptr<T>(items: &[T]) -> *const T {
    if items.is_empty() {
        ptr::null()
    } else {
        items.as_ptr()
    }
}

/// The walk options a C caller asked for: each zero field is the default.
fn walk_options(root: &OsStr, options: Option<&TessScanOptions>) -> WalkOptions {
    let mut walk = WalkOptions {
        root: PathBuf::from(root),
        ..WalkOptions::default()
    };
    let Some(o) = options else { return walk };
    if o.max_depth != 0 {
        walk.max_depth = o.max_depth;
    }
    walk.include_non_local = o.include_non_local != 0;
    if o.workers != 0 {
        walk.workers = o.workers as usize;
    }
    if o.node_budget != 0 {
        walk.node_budget = o.node_budget;
    }
    if o.buffer_bytes != 0 {
        walk.buffer_bytes = usize::try_from(o.buffer_bytes).unwrap_or(usize::MAX);
    }
    if o.stall_timeout_ms != 0 {
        walk.stall_timeout = Duration::from_millis(o.stall_timeout_ms);
    }
    walk
}

/// The stable code for why a scan is partial. Exhaustive, so a new core
/// variant is a compile error here rather than a reason the app cannot name.
fn incomplete_code(reason: Option<Incomplete>) -> u32 {
    match reason {
        None => TESS_INCOMPLETE_NONE,
        Some(Incomplete::Cancelled) => TESS_INCOMPLETE_CANCELLED,
        Some(Incomplete::NodeBudget) => TESS_INCOMPLETE_NODE_BUDGET,
        Some(Incomplete::OutOfMemory) => TESS_INCOMPLETE_OUT_OF_MEMORY,
        Some(Incomplete::Stalled) => TESS_INCOMPLETE_STALLED,
        Some(Incomplete::FdExhausted) => TESS_INCOMPLETE_FD_EXHAUSTED,
        Some(Incomplete::MalformedBatch) => TESS_INCOMPLETE_MALFORMED_BATCH,
        Some(Incomplete::VolumeLost) => TESS_INCOMPLETE_VOLUME_LOST,
    }
}

/// Every count of the walk's that a UI would show. The lists (`unreadable`,
/// `skipped_mounts`) become their lengths: the app shows "3 folders could not
/// be read", and the paths stay in the snapshot for a later accessor.
fn scan_stats(walk: &WalkStats) -> TessScanStats {
    TessScanStats {
        incomplete: incomplete_code(walk.incomplete),
        files: walk.files,
        dirs: walk.dirs,
        errors: walk.errors,
        unreadable_count: walk.unreadable.len() as u64,
        skipped_mounts_count: walk.skipped_mounts.len() as u64,
        lost_entries: walk.lost_entries,
        hardlink_dups: walk.hardlink_dups,
        depth_capped: walk.depth_capped,
    }
}

/// A negated errno for a failed scan: the OS error number if the error carries
/// one, directly or inside the context core wraps around it (see
/// `tesserae_core::walk::os_errno`), otherwise one chosen from its kind.
///
/// The number is what the app needs, not the kind: `EACCES` and `EPERM` are
/// both `PermissionDenied`, and on macOS only `EPERM` is the privacy layer
/// refusing access, which Full Disk Access can fix. So a `PermissionDenied`
/// that has lost its number is `EIO` ("unknown"), not a guess at `EACCES`; the
/// kinds that follow are each one errno.
fn errno_of(e: &io::Error) -> i32 {
    use io::ErrorKind::*;
    let errno = os_errno(e)
        .filter(|&n| n > 0)
        .unwrap_or_else(|| match e.kind() {
            NotFound => libc::ENOENT,
            NotADirectory => libc::ENOTDIR,
            InvalidInput => libc::EINVAL,
            OutOfMemory => libc::ENOMEM,
            _ => libc::EIO,
        });
    -errno
}

/// The name the scan thread runs under, visible in a debugger or a sample.
const SCAN_THREAD: &str = "tesserae-scan";

/// Spawn the scan thread. One fresh `Progress` per scan: a cancel is never
/// undone, so a `Progress` cannot be handed to a second walk.
fn start(opts: WalkOptions) -> io::Result<TessScan> {
    let progress = Arc::new(Progress::default());
    let status = Arc::new(AtomicI32::new(TESS_STATUS_RUNNING));
    let thread = std::thread::Builder::new()
        .name(SCAN_THREAD.to_owned())
        .spawn({
            let (progress, status) = (Arc::clone(&progress), Arc::clone(&status));
            move || scan_thread(&opts, &progress, &status)
        })?;
    Ok(TessScan {
        progress,
        status,
        thread,
    })
}

/// The scan thread's body: walk, freeze, publish the outcome as the status.
///
/// The walk and freeze run inside `catch_unwind`, so a panic in either, or one
/// resumed from a worker (see the crate docs), is a failed scan rather than a
/// dead thread whose status would read "running" for ever.
fn scan_thread(
    opts: &WalkOptions,
    progress: &Progress,
    status: &AtomicI32,
) -> Result<Snapshot, i32> {
    let result = guarded(Err(-libc::EIO), || {
        let (arenas, stats) = walk_with_progress(opts, progress).map_err(|e| errno_of(&e))?;
        // `try_freeze`, never `freeze`: an allocation failure is a failed scan.
        try_freeze(arenas, stats).map_err(|_| -libc::ENOMEM)
    });
    let outcome = match &result {
        Ok(_) => TESS_STATUS_FINISHED,
        Err(errno) => *errno,
    };
    status.store(outcome, Ordering::Release);
    result
}

