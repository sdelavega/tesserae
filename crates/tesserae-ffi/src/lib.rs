    const GARBAGE: u8 = 0xA5;

    fn c_root(root: &Path) -> CString {
        CString::new(root.as_os_str().as_bytes()).unwrap()
    }

    fn begin(root: &Path, options: Option<&TessScanOptions>) -> *mut TessScan {
        let root = c_root(root);
        let options = options.map_or(ptr::null(), |o| o as *const TessScanOptions);
        // SAFETY: `root` is a live NUL-terminated string and `options` is null
        // or points at a live struct.
        let scan = unsafe { tess_scan_begin(root.as_ptr(), options) };
        assert!(!scan.is_null(), "tess_scan_begin refused a usable root");
        scan
    }

    fn status(scan: *const TessScan) -> i32 {
        // SAFETY: every caller passes a scan it has not yet finished.
        unsafe { tess_scan_status(scan) }
    }

    /// The status once the scan has left `running`.
    fn wait(scan: *const TessScan) -> i32 {
        let started = Instant::now();
        loop {
            match status(scan) {
                TESS_STATUS_RUNNING => {
                    assert!(started.elapsed() < WAIT, "the scan is still running");
                    std::thread::sleep(Duration::from_millis(5));
                }
                s => return s,
            }
        }
    }

    fn finish(scan: *mut TessScan) -> *mut TessSnapshot {
        // SAFETY: every caller passes a scan it has not yet finished and
        // never touches it again.
        unsafe { tess_scan_finish(scan) }
    }

    /// Scan `root` to completion and return its snapshot, which must exist.
    fn scan(root: &Path, options: Option<&TessScanOptions>) -> *mut TessSnapshot {
        let scan = begin(root, options);
        assert_eq!(wait(scan), TESS_STATUS_FINISHED);
        let snapshot = finish(scan);
        assert!(!snapshot.is_null(), "a finished scan yielded no snapshot");
        snapshot
    }

    fn release(snapshot: *mut TessSnapshot) {
        // SAFETY: every caller passes a snapshot it has not yet released and
        // never touches it again.
        unsafe { tess_snapshot_release(snapshot) }
    }

