//! The C ABI over the scan engine: what the SwiftUI app links.
//!
//! `tesserae.h` (generated by `scripts/gen-header.sh`) is the contract; this
//! file is its source. A scan runs on a thread of its own, so `tess_scan_begin`
//! returns at once and the app polls `tess_scan_progress` and `tess_scan_status`
//! from its main thread. `tess_scan_finish` consumes the scan and returns the
//! frozen snapshot: one immutable allocation the app reads through
//! `tess_snapshot_view` until it calls `tess_snapshot_release`.
//!
//! # Building the library the app links
//!
//! Build it with exactly `cargo build -p tesserae-ffi --release`. The tests
//! turn on tesserae-core's `test-hooks` feature through a dev-dependency, and
//! cargo's feature resolution only keeps that out of a build that does not
//! build test targets: `--all-targets`, `--tests` or `cargo test --release`
//! would unify the hooks into the library (inert unless armed, but every worker
//! task would then take a lock). `scripts/check-shipped-lib.sh` verifies the
//! result.
//!
//! # Panics never cross the boundary
//!
//! Every `extern "C"` body runs inside `catch_unwind`, and so does the scan
//! thread's whole walk-and-freeze. The walk's own workers are core's threads: a
//! worker that panics raises the shared halt and the panic is resumed on the
//! thread that called the walk, which here is the scan thread, so its guard
//! catches it; it is reported as a failed scan (`-EIO` from `tess_scan_status`,
//! null from `tess_scan_finish`). That relies on `panic = "unwind"`, pinned in
//! the workspace's release profile: with `abort`, a bad symlink would kill the
//! app.

